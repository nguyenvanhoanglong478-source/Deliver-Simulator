"""Pause button tests. Run: python3 tests/test_pause.py"""
import os
URL="file://"+os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","index.html"))
from playwright.sync_api import sync_playwright
res=[]
def ok(n,c,x=''): res.append(('PASS' if c else 'FAIL',n,x))
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(); errs=[]
    pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(URL); pg.evaluate("localStorage.clear();localStorage.setItem(\x27btd_tut\x27,\x271\x27)"); pg.reload()
    pg.evaluate("startGame(true)")
    ok('button hidden on start screen? (visible in game)',pg.is_visible('#pause-btn'))
    pg.click('#pause-btn')
    ok('pause modal open',pg.evaluate("modal&&modal.type==='pause'"))
    ok('button hidden while paused',not pg.is_visible('#pause-btn'))
    t=pg.evaluate("g.dayTimeLeft"); pg.wait_for_timeout(2500)
    ok('day clock frozen',pg.evaluate("g.dayTimeLeft")==t)
    pg.click("text=ÂM THANH"); ok('settings from pause',pg.evaluate("modal.type==='settings'&&modal.from==='pause'"))
    pg.click("text=ĐÓNG"); ok('close settings returns to pause',pg.evaluate("modal&&modal.type==='pause'"))
    pg.click("text=TIẾP TỤC"); ok('resume closes modal',pg.evaluate("modal===null"))
    pg.wait_for_timeout(2300); ok('clock runs again',pg.evaluate("g.dayTimeLeft")<t)
    pg.keyboard.press('p'); ok('P key pauses',pg.evaluate("modal&&modal.type==='pause'"))
    pg.keyboard.press('Escape'); ok('Esc resumes',pg.evaluate("modal===null"))
    # delivery
    pg.evaluate("g.stamina=100;g.fuel=100;g.offers[0]={type:'food',dist:2,rush:false,peak:false,base:50000};doDelivery(0)")
    ok('button visible during delivery',pg.is_visible('#pause-btn'))
    pg.wait_for_timeout(1000); pg.click('#pause-btn')
    tl=pg.evaluate("dlvLeft()"); pg.wait_for_timeout(3000)
    ok('delivery timer frozen',abs(pg.evaluate("dlvLeft()")-tl)<0.01 and pg.evaluate("!!DLV"))
    ok('card still shows the progress bar while paused',pg.locator('#dl-bar').count()==1)
    pg.keyboard.press('p'); pg.wait_for_timeout(1000)
    tl2=pg.evaluate("dlvLeft()")
    ok('delivery resumes without losing the paused time',tl2<tl and tl-tl2<1.6,f"{tl}->{tl2}")
    pg.evaluate("stopT(dlvTmr);DLV=null;g.activeAnim=null;g.phase='game';render()")
    # ===== back to the start screen from the pause menu =====
    pg.evaluate("stopT(dlvTmr);DLV=null;g.activeAnim=null;g.phase='game';modal=null;GT.paused=false;render()")
    pg.evaluate("g.cash=1234567;save()")
    pg.keyboard.press('p'); ok('pause menu has the home option','VỀ MÀN HÌNH BẮT ĐẦU' in pg.inner_text('body'))
    pg.click("text=VỀ MÀN HÌNH BẮT ĐẦU"); ok('asks for confirmation',pg.evaluate("modal&&modal.type==='confirmHome'") and 'VỀ MÀN HÌNH BẮT ĐẦU?' in pg.inner_text('body'))
    pg.click("text=Ở LẠI"); ok('stay returns to pause menu',pg.evaluate("modal&&modal.type==='pause'"))
    pg.click("text=VỀ MÀN HÌNH BẮT ĐẦU"); pg.keyboard.press('Escape'); ok('Esc cancels the confirmation',pg.evaluate("modal&&modal.type==='pause'"))
    pg.click("text=VỀ MÀN HÌNH BẮT ĐẦU"); pg.click("text=VỀ MÀN HÌNH >> nth=-1")
    ok('start screen shown, clock stopped',pg.evaluate("g.phase==='start'&&modal===null&&!GT.paused&&GT.tasks.length===0") and 'TIẾP TỤC' in pg.inner_text('body') and 'BẮT ĐẦU MỚI' in pg.inner_text('body'))
    ok('pause button hidden on start screen',pg.evaluate("document.getElementById('pause-btn').hidden"))
    t=pg.evaluate("g.dayTimeLeft"); pg.wait_for_timeout(1500); ok('time does not run on start screen',pg.evaluate("g.dayTimeLeft")==t)
    pg.click("text=TIẾP TỤC"); pg.wait_for_timeout(300)
    ok('continue restores the saved game',pg.evaluate("g.phase==='game'&&g.cash===1234567"))
    # from a delivery: the unfinished order is cancelled, last save restored
    pg.evaluate("g.stamina=100;g.fuel=100;g.offers[0]={type:'goods',dist:1,rush:false,peak:false,base:80000};doDelivery(0)")
    pg.keyboard.press('p')
    ok('home option also in delivery pause','VỀ MÀN HÌNH BẮT ĐẦU' in pg.inner_text('body'))
    pg.click("text=VỀ MÀN HÌNH BẮT ĐẦU"); ok('delivery warning text','bị hủy' in pg.inner_text('body')); pg.click("text=VỀ MÀN HÌNH >> nth=-1")
    ok('delivery stopped',pg.evaluate("g.phase==='start'&&DLV===null&&GT.tasks.length===0"))
    pg.click("text=TIẾP TỤC"); pg.wait_for_timeout(300)
    ok('continue after leaving a delivery: game screen, resources stay spent (same as a reload)',pg.evaluate("g.phase==='game'&&g.stamina<100&&g.cash===1234567"),str(pg.evaluate("[g.phase,g.stamina,g.fuel]")))
    # light pause (animation phases)
    pg.evaluate("g.phase='anim-sleep';g.activeAnim={};GT.paused=false;modal=null;pausedLight=false;render();pauseGame()")
    ok('light pause has home option',pg.evaluate("pausedLight")and 'VỀ MÀN HÌNH BẮT ĐẦU' in pg.inner_text('#pause-ov'))
    pg.click("#pause-ov >> text=VỀ MÀN HÌNH BẮT ĐẦU"); ok('light: confirm shown, overlay hidden',pg.evaluate("modal&&modal.type==='confirmHome'&&document.getElementById('pause-ov').hidden"))
    pg.click("text=Ở LẠI"); ok('light: stay brings the pause overlay back',pg.evaluate("pausedLight&&!document.getElementById('pause-ov').hidden"))
    pg.evaluate("askHome()"); pg.evaluate("goHome()"); ok('light: leaves to start',pg.evaluate("g.phase==='start'&&!pausedLight&&!GT.paused"))
    ok('no page errors',not errs,str(errs))
    b.close()
for r in res: print(*r)
print(sum(r[0]=='PASS' for r in res),'/',len(res))
