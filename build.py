"""Build the game.
  python3 build.py                      -> index.html (music + fonts loaded from src/, works on GitHub Pages and offline via sw.js)
  python3 build.py --artifact FILE.html -> also writes a fully self-contained page (music, fonts and bike embedded) for Claude artifacts
"""
import sys,base64,os,hashlib,json
os.chdir(os.path.dirname(os.path.abspath(__file__)))
def rd(p,m='r'):
    return open(p,m,encoding=None if 'b' in m else 'utf8').read()
def b64(p,mime): return f'data:{mime};base64,'+base64.b64encode(rd(p,'rb')).decode()

BIKE=b64('src/bike.png','image/png')
AUDIO=(('__MUSIC__','src/music.mp3'),('__T1__','src/track1.mp3'),('__T2__','src/track2.mp3'),('__T3__','src/track3.mp3'),('__T4__','src/track4.mp3'))
FONTS=(('__F_VT_LATIN__','src/fonts/vt323-latin-400-normal.woff2'),('__F_VT_EXT__','src/fonts/vt323-latin-ext-400-normal.woff2'),
       ('__F_VT_VI__','src/fonts/vt323-vietnamese-400-normal.woff2'),('__F_PS_LATIN__','src/fonts/press-start-2p-latin-400-normal.woff2'))
JS_FILES=['src/loop.js','src/icons.js','src/audio.js','src/profile.js','src/logic.js','src/state.js','src/render.js']
CSS=rd('src/style.css')

def make(embed):
    js=''.join(rd(f)+'\n' for f in JS_FILES).replace('__BIKE__',BIKE)
    fc=rd('src/fonts.css')
    for k,f in AUDIO: js=js.replace(k,b64(f,'audio/mpeg') if embed else f)
    for k,f in FONTS: fc=fc.replace(k,b64(f,'font/woff2') if embed else f)
    body=('<div id="root"></div>\n<div id="toast"></div>\n<button id="pause-btn" onclick="pauseGame()" aria-label="Tạm dừng" hidden></button>\n'
          '<button id="snd-btn" onclick="openSettings()" hidden></button>\n'
          '<canvas id="fx" aria-hidden="true"></canvas>\n<div id="pause-ov" class="overlay" hidden></div>\n<script>\n'+js+'</script>\n')
    return fc+'\n'+CSS,body

title='<title>Be The Driver</title>'
css,body=make(False)
sw_ver=hashlib.sha1((css+body).encode()).hexdigest()[:10]
reg=("<script>if('serviceWorker'in navigator&&location.protocol.startsWith('http')){addEventListener('load',()=>navigator.serviceWorker.register('sw.js').catch(()=>{}))}</script>\n")
head=('<meta charset="UTF-8">\n<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
      '<meta name="theme-color" content="#0a0814">\n<link rel="manifest" href="manifest.webmanifest">\n<link rel="icon" href="src/icon-192.png">\n'
      '<link rel="preload" href="src/fonts/vt323-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin>\n')
full=f'<!DOCTYPE html>\n<html lang="vi">\n<head>\n{head}{title}\n<style>\nhtml{{color-scheme:dark}}\n{css}</style>\n</head>\n<body>\n{body}{reg}</body>\n</html>\n'
open('index.html','w',encoding='utf8').write(full)

# service worker: precache the shell, cache music on first play (with Range support so <audio> can seek)
assets=['./','index.html','manifest.webmanifest','src/icon-192.png','src/icon-512.png']+[f for _,f in FONTS]
media=[f for _,f in AUDIO]
open('sw.js','w',encoding='utf8').write(f"""// generated by build.py
const CACHE='btd-{sw_ver}',CORE={json.dumps(assets)},MEDIA={json.dumps(media)};
self.addEventListener('install',e=>{{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(CORE)).then(()=>self.skipWaiting()))}});
self.addEventListener('activate',e=>{{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==CACHE&&k.startsWith('btd-')).map(k=>caches.delete(k)))).then(()=>self.clients.claim()))}});
async function ranged(req,res){{
  const m=/bytes=(\\d*)-(\\d*)/.exec(req.headers.get('range')||'');
  if(!m)return res;
  const buf=await res.arrayBuffer(),n=buf.byteLength;
  const s=m[1]?+m[1]:0,t=m[2]?Math.min(+m[2],n-1):n-1;
  return new Response(buf.slice(s,t+1),{{status:206,statusText:'Partial Content',headers:{{'Content-Type':res.headers.get('Content-Type')||'audio/mpeg','Content-Range':`bytes ${{s}}-${{t}}/${{n}}`,'Content-Length':String(t-s+1),'Accept-Ranges':'bytes'}}}});
}}
self.addEventListener('fetch',e=>{{
  const r=e.request;if(r.method!=='GET')return;
  const u=new URL(r.url);if(u.origin!==location.origin)return;
  e.respondWith((async()=>{{
    const c=await caches.open(CACHE);
    let hit=await c.match(u.pathname,{{ignoreSearch:true}})||await c.match(r.url);
    if(!hit){{
      try{{
        const full=await fetch(u.pathname.endsWith('.mp3')?new Request(r.url):r);   // fetch whole file once so it can be cached and range-served
        if(full.ok&&full.status===200){{c.put(r.url,full.clone());hit=full}}else return full;
      }}catch(err){{return hit||Response.error()}}
    }}
    return r.headers.has('range')?ranged(r,hit.clone()):hit;
  }})());
}});
""")
open('manifest.webmanifest','w',encoding='utf8').write(json.dumps({"name":"Be The Driver","short_name":"Be The Driver","start_url":"./","display":"standalone",
  "background_color":"#0a0814","theme_color":"#0a0814","lang":"vi","icons":[{"src":"src/icon-192.png","sizes":"192x192","type":"image/png"},{"src":"src/icon-512.png","sizes":"512x512","type":"image/png"}]},indent=1))
print('built index.html',len(full)//1024,'KB')

if '--artifact' in sys.argv:
    out=sys.argv[sys.argv.index('--artifact')+1]
    css,body=make(True)
    open(out,'w',encoding='utf8').write(f'{title}\n<style>\n{css}</style>\n{body}')
    print('built artifact',out,os.path.getsize(out)//1024,'KB')
